# The present script "GenerateConstantFile2D" helps in generating a file
# of the form x y c1 c2 c3 ... cN or x y c1 M1 c2 M2 c3 M3 ... cN MN
# where x is the discretization of the spatial domain [0,L] with a space step dx
# and Nx=L*dx points inside the domain (x=[dx/2, 3dx/2, ... L-dx/2]) 
# y is the discretization of the spatial domain [0,l] with a space step dy
# and Ny=l*dy points inside the domain (y=[dy/2, 3dy/2, ... L-dy/2]) 
# corresponding to the FullSWOF discretization on [0,L]x[0,l]; 
# the ci, Mi does not change with respect to x and y.
# This type of file is used in the transfer model, for initial conditions
# or other initializations.
##################################################################################

SCRIPTVERSION="1.00.00, 2023-01-26"

# Define output flux
STDERR=2

if [ $# -lt 3 ]; then
echo "Usage:    GenerateConstantFile2D.sh Nx Ny L l c1 c2 c3 ... cN" >&$STDERR
	echo "Version $SCRIPTVERSION" >&$STDERR
	echo "GenerateConstantFile2D.sh helps in generating a file of the form x y c1 c2 c3 ... cN
where x is the discretization of the spatial domain [0,L] with Nx=L*dx points inside the domain
(x=[dx/2, 3dx/2, ... L-dx/2]), y is the discretization of the spatial domain [0,l] with Ny=l*dy points inside the domain
(y=[dy/2, 3dy/2, ... L-dy/2]) corresponding to the FullSWOF discretization on [0,L]x[0,l];
the ci, Mi does not change with respect to x and y.">&$STDERR
	echo "This type of file is used for initial conditions or other initializations.">&$STDERR
	exit 1;
fi;

#Read input values
## Values from the FullSWOF space discretization
NX=$1;
NY=$2;
L=$3;
l=$4;
DX=$L/$NX; # dx = L/Nx
DY=$l/$NY; # dy = l/NY
## Values of "c1 c2 c3 ... cN"
VALUES=${@:5:$(($#-1))}

# results are saved with 5 digits, it can be changed in the scale value.

echo "##############################################################################"
echo "# Generated by GenerateConstantFile2D version $SCRIPTVERSION"
echo "# on $(date "+%Y-%m-%d %H:%M:%S") ($(id -un)@$(hostname))"
echo "##############################################################################"
for i in `seq 1 $NX.`;
do
	for j in `seq 1 $NY.`;
		do
		x=$(echo "scale=5;($i-1)*$DX+$DX/2." | bc)
		y=$(echo "scale=5;($j-1)*$DY+$DY/2." | bc)
		echo "$x $y $VALUES"
	done;
	echo " "
done;

exit 0;
